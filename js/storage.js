// ============================================================
// storage.js — тонкий слой доступа к хранилищу.
//
// Единственная точка, где код обращается к localStorage напрямую.
// При переезде на бэкенд достаточно заменить тело этих методов
// (например, на HTTP-вызовы), не трогая остальные модули.
//
// Вешается на App.storage (имя window.Storage занято встроенным
// конструктором браузера, перезаписывать его нельзя).
// ============================================================
(function() {
    const backend = window.localStorage;

    App.storage = {
        /**
         * Сохранить значение под ключом (сериализуется в JSON).
         */
        save(key, value) {
            backend.setItem(key, JSON.stringify(value));
        },

        /**
         * Прочитать и распарсить значение.
         * Возвращает null, если ключа нет или JSON повреждён
         * (тихо, как это делали loadButtonStyle и т.п.).
         */
        load(key) {
            const raw = backend.getItem(key);
            if (raw === null) return null;
            try {
                return JSON.parse(raw);
            } catch (e) {
                return null;
            }
        },

        /**
         * Прочитать сырую строку без парсинга (для вызывающих,
         * которым нужен собственный разбор/обработка ошибок).
         * Возвращает строку или null.
         */
        loadRaw(key) {
            return backend.getItem(key);
        },

        /**
         * Записать сырую строку как есть, без JSON-сериализации.
         * Нужно для сохранения точной копии повреждённых данных
         * (двойное кодирование исказило бы исходную строку).
         */
        saveRaw(key, rawString) {
            backend.setItem(key, rawString);
        },

        /**
         * Удалить ключ из хранилища.
         */
        remove(key) {
            backend.removeItem(key);
        }
    };
})();
